-- 1. TABEL BERITA & PENGUMUMAN
CREATE TABLE IF NOT EXISTS public.berita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul VARCHAR(255) NOT NULL,
    slug VARCHAR(255) UNIQUE,
    ringkasan TEXT,
    isi TEXT NOT NULL,
    kategori VARCHAR(50) DEFAULT 'Pembangunan', -- Pembangunan, Kesehatan, Ekonomi, Kegiatan
    gambar TEXT,
    penulis VARCHAR(100) DEFAULT 'Admin Desa Tajemsari',
    tanggal DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. TABEL PERMOHONAN SURAT WARGA (LAYANAN PUBLIK)
CREATE TABLE IF NOT EXISTS public.permohonan_surat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomor_tiket VARCHAR(20) UNIQUE NOT NULL,
    nama_warga VARCHAR(150) NOT NULL,
    nik VARCHAR(16) NOT NULL,
    no_hp VARCHAR(20) NOT NULL,
    rt_rw VARCHAR(20) NOT NULL,
    jenis_surat VARCHAR(100) NOT NULL, -- Surat Keterangan Usaha, Domisili, SKTM, dll.
    keperluan TEXT NOT NULL,
    status VARCHAR(30) DEFAULT 'Menunggu' CHECK (status IN ('Menunggu', 'Diproses', 'Selesai', 'Ditolak')),
    catatan_admin TEXT,
    tanggal_pengajuan TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. TABEL POTENSI UMKM DESA
CREATE TABLE IF NOT EXISTS public.umkm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_produk VARCHAR(150) NOT NULL,
    kategori VARCHAR(50) DEFAULT 'Pertanian', -- Pertanian, Kuliner, Kerajinan, Olahan Madu
    pembuat VARCHAR(100) NOT NULL,
    harga VARCHAR(50),
    deskripsi TEXT,
    wa_seller VARCHAR(20),
    gambar TEXT,
    lokasi VARCHAR(100) DEFAULT 'Desa Tajemsari, Tegowanu',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. TABEL DESTINASI WISATA & POTENSI ALAM
CREATE TABLE IF NOT EXISTS public.wisata (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_tempat VARCHAR(150) NOT NULL,
    kategori VARCHAR(50) DEFAULT 'Wisata Alam',
    deskripsi TEXT NOT NULL,
    lokasi VARCHAR(150) NOT NULL,
    jam_buka VARCHAR(100),
    tiket_masuk VARCHAR(50) DEFAULT 'Gratis',
    gambar TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. TABEL PERANGKAT DESA / STRUKTUR ORGANISASI
CREATE TABLE IF NOT EXISTS public.perangkat_desa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(150) NOT NULL,
    jabatan VARCHAR(100) NOT NULL,
    foto TEXT,
    urutan INT DEFAULT 0
);

