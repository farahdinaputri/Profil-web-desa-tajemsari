-- KETENTUAN ROW LEVEL SECURITY (RLS) - PUBLIC BISA READ, ADMIN BISA READ/WRITE
ALTER TABLE public.berita ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.permohonan_surat ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.umkm ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wisata ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public Read Berita" ON public.berita FOR SELECT USING (true);
CREATE POLICY "Public Read UMKM" ON public.umkm FOR SELECT USING (true);
CREATE POLICY "Public Read Wisata" ON public.wisata FOR SELECT USING (true);
CREATE POLICY "Public Insert Permohonan" ON public.permohonan_surat FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Select Own Permohonan" ON public.permohonan_surat FOR SELECT USING (true);

-- Admin Full Access (If using Supabase Auth authenticated role)
CREATE POLICY "Admin Full Access Berita" ON public.berita FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Admin Full Access Permohonan" ON public.permohonan_surat FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Admin Full Access UMKM" ON public.umkm FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Admin Full Access Wisata" ON public.wisata FOR ALL USING (auth.role() = 'authenticated');
