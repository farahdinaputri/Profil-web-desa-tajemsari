-- 1. TABEL ADMIN USERS (LOGIN PENGURUS/ADMIN DESA)
CREATE TABLE IF NOT EXISTS public.admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  nama_lengkap TEXT,
  email TEXT,
  role TEXT DEFAULT 'Admin Utama',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. TABEL HERO SECTION & FOTO KADES (BERANDA UTAMA)
CREATE TABLE IF NOT EXISTS public.hero_section (
  id INT PRIMARY KEY DEFAULT 1,
  badge TEXT,
  judul TEXT NOT NULL,
  deskripsi TEXT,
  bg_image TEXT DEFAULT '',
  kades_nama TEXT,
  kades_jabatan TEXT,
  kades_periode TEXT,
  kades_foto TEXT DEFAULT '',
  kades_sambutan TEXT,
  stat_penduduk TEXT,
  stat_rt_rw TEXT,
  stat_umkm TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. TABEL PROFIL DESA (SEJARAH, VISI & MISI, PERANGKAT DESA)
CREATE TABLE IF NOT EXISTS public.profil_desa (
  id INT PRIMARY KEY DEFAULT 1,
  sejarah_judul TEXT,
  sejarah_paragraf1 TEXT,
  sejarah_paragraf2 TEXT,
  visi_judul TEXT,
  visi_deskripsi TEXT,
  misi_list JSONB DEFAULT '[]'::jsonb,
  perangkat_list JSONB DEFAULT '[]'::jsonb,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. TABEL BERITA DESA
CREATE TABLE IF NOT EXISTS public.berita (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul TEXT NOT NULL,
  slug TEXT,
  kategori TEXT,
  penulis TEXT,
  tanggal DATE DEFAULT CURRENT_DATE,
  ringkasan TEXT,
  isi TEXT,
  gambar TEXT DEFAULT '',
  galeri JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. TABEL PRODUK UMKM DESA
CREATE TABLE IF NOT EXISTS public.umkm (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_produk TEXT NOT NULL,
  kategori TEXT,
  pembuat TEXT,
  dusun TEXT,
  harga TEXT,
  wa_seller TEXT,
  deskripsi TEXT,
  gambar TEXT DEFAULT '',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. TABEL DESTINASI WISATA DESA
CREATE TABLE IF NOT EXISTS public.wisata (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_tempat TEXT NOT NULL,
  kategori TEXT,
  lokasi TEXT,
  jam_buka TEXT,
  tiket_masuk TEXT,
  deskripsi TEXT,
  gambar TEXT DEFAULT '',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. TABEL LAYANAN PERMOHONAN SURAT ONLINE WARGA
CREATE TABLE IF NOT EXISTS public.permohonan_surat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor_tiket TEXT UNIQUE NOT NULL,
  nama_warga TEXT NOT NULL,
  nik TEXT NOT NULL,
  no_hp TEXT,
  alamat_lengkap TEXT,
  jenis_surat TEXT NOT NULL,
  keperluan TEXT,
  status TEXT DEFAULT 'Menunggu Verifikasi',
  catatan_admin TEXT,
  tanggal_pengajuan TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  file_surat_url TEXT DEFAULT '',
  file_surat_name TEXT DEFAULT '',
  metode_pengambilan TEXT DEFAULT 'Digital',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 8. TABEL INFORMASI FOOTER & KONTAK
CREATE TABLE IF NOT EXISTS public.footer_info (
  id INT PRIMARY KEY DEFAULT 1,
  alamat TEXT,
  telepon TEXT,
  whatsapp TEXT,
  email TEXT,
  jam_pelayanan TEXT,
  maps_url TEXT,
  facebook TEXT,
  instagram TEXT,
  youtube TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 9. TABEL PENGATURAN WEBSITE
CREATE TABLE IF NOT EXISTS public.website_settings (
  id INT PRIMARY KEY DEFAULT 1,
  nama_desa TEXT,
  kecamatan TEXT,
  kabupaten TEXT,
  provinsi TEXT,
  email_admin TEXT,
  telepon_kantor TEXT,
  running_text TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

